// Mechanical standalone mirror. Docker copies only apps/api; no production workspace TS import or new dependency.
// Run from any cwd: node apps/api/scripts/sync-puzzle-adapter.mjs [--check]. Tests check exact parity with the pure source.
import { readFile, mkdir, writeFile, readdir, unlink } from 'node:fs/promises'
import { dirname, resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'
const api = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = resolve(api, '../../packages/domain/src'), target = resolve(api, 'src/save/puzzle-domain')
const generated = new Map()
async function visit(file) {
  if (generated.has(file)) return
  const body = await readFile(file, 'utf8')
  generated.set(file, body)
  const ast = ts.createSourceFile(file, body, ts.ScriptTarget.Latest, true)
  for (const node of ast.statements) {
    if (!(ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) || !node.moduleSpecifier || !ts.isStringLiteral(node.moduleSpecifier)) continue
    const spec = node.moduleSpecifier.text
    if (!spec.startsWith('.')) throw new Error(`Non-pure dependency in standalone Puzzle adapter: ${spec}`)
    let dependency = resolve(dirname(file), `${spec}.ts`)
    try { await readFile(dependency) } catch { dependency = resolve(dirname(file), spec, 'index.ts') }
    if (!dependency.startsWith(`${source}/`)) throw new Error('Adapter dependency escaped domain')
    await visit(dependency)
  }
}
await visit(resolve(source, 'minigames/uma-puzzles/operations.ts'))
await visit(resolve(source, 'minigames/uma-puzzles/preservation.ts'))
await visit(resolve(source, 'minigames/uma-puzzles/content.ts'))
await visit(resolve(source, 'minigames/uma-puzzles/legacy-spark.ts'))
for (const [path, body] of generated) {
  const output = resolve(target, relative(source, path)), content = `// GENERATED by apps/api/scripts/sync-puzzle-adapter.mjs; edit the domain source, then regenerate.\n${body}`
  if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== content) throw new Error(`Stale standalone adapter: ${relative(target, output)}`)
  } else { await mkdir(dirname(output), { recursive: true }); await writeFile(output, content) }
}
async function files(folder) {
  const entries = await readdir(folder, { withFileTypes: true })
  return (await Promise.all(entries.map(e => e.isDirectory() ? files(resolve(folder, e.name)) : [resolve(folder, e.name)]))).flat()
}
const expected = new Set([...generated.keys()].map(p => resolve(target, relative(source, p))))
for (const path of await files(target)) if (!expected.has(path)) {
  if (process.argv.includes('--check') || !(await readFile(path, 'utf8')).startsWith('// GENERATED by apps/api/scripts/sync-puzzle-adapter.mjs;'))
    throw new Error(`Unexpected adapter file: ${path}`)
  // Only stale generated copies under this exact adapter directory, never user-authored files.
  await unlink(path)
}
console.log(`Standalone Puzzle adapter ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${generated.size} pure TypeScript modules`)
